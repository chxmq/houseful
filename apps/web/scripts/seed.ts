function buildEvents(): NewEvent[] {
  let nextChainId = 1;
  return eventSeeds.map((e) => {
    const startsAt = ist(...(e.start as [number, number, number, number, number?]));
    const endsAt = e.end ? ist(...e.end) : startsAt + e.durationMins * 60;
    if (e.sold > e.capacity) throw new Error(`${e.slug}: sold exceeds capacity`);
    if (e.status === "sold_out" && e.sold !== e.capacity) throw new Error(`${e.slug}: sold_out must be full`);
    if (e.status === "announced" && e.sold !== 0) throw new Error(`${e.slug}: announced must have no sales`);
    return {
      id: e.slug,
      chainEventId: e.city === "mumbai" ? nextChainId++ : null,
      title: e.title,
      subtitle: e.subtitle,
      category: e.category,
      citySlug: e.city,
      venueId: e.venue,
      hostId: e.host,
      startsAt,
      doorsAt: startsAt - e.doorsBeforeMins * 60,
      endsAt,
      priceUsd: e.priceUsd,
      faceValueUnits: usdToUnits(e.priceUsd),
      seated: false,
      officialUrl: "",
      sourceUrl: "",
      capacity: e.capacity,
      sold: e.sold,
      status: e.status,
      featured: e.featured ?? false,
      ageLimit: e.ageLimit,
      language: e.language,
      durationMins: e.durationMins,
      description: e.description.join("\n\n"),
      lineup: e.lineup,
      highlights: e.highlights,
      posterVariant: e.posterVariant,
      posterInk: e.posterInk,
      surrenderCutoffHours: e.surrenderCutoffHours,
    };
  });
}

function assertCleanCopy(rows: NewEvent[]) {
  const banned = /[\u2014\u2013]|unforgettable|electrifying|immersive|vibrant|lorem/i;
  for (const row of rows) {
    const text = [row.title, row.subtitle, row.description, ...row.lineup, ...row.highlights].join(" ");
    if (banned.test(text)) throw new Error(`${row.id}: copy breaks the style rules`);
  }
}

async function main() {
  const eventRows = buildEvents();
  assertCleanCopy(eventRows);

  const venueRows: NewVenue[] = venueSeeds.map((v) => ({ ...v, id: v.slug }));
  const hostRows: NewHost[] = hostSeeds.map((h) => ({ ...h, id: h.slug, payoutAddress: null }));

  for (const row of eventRows) {
    const venue = venueRows.find((v) => v.id === row.venueId);
    if (!venue) throw new Error(`${row.id}: unknown venue ${row.venueId}`);
    if (venue.citySlug !== row.citySlug) throw new Error(`${row.id}: venue is in another city`);
    if (row.capacity > venue.capacity) throw new Error(`${row.id}: capacity exceeds venue`);
    if (!hostRows.some((h) => h.id === row.hostId)) throw new Error(`${row.id}: unknown host ${row.hostId}`);
  }

  await db.transaction(async (tx) => {
    await tx.delete(events);
    await tx.delete(hosts);
    await tx.delete(venues);
    await tx.delete(cities);
    await tx.insert(cities).values(cityRows);
    await tx.insert(venues).values(venueRows);
    await tx.insert(hosts).values(hostRows);
    await tx.insert(events).values(eventRows);
  });

  const mumbai = eventRows.filter((e) => e.citySlug === "mumbai").length;
  console.log(
    `Seeded ${cityRows.length} cities, ${venueRows.length} venues, ${hostRows.length} hosts, ${eventRows.length} events (${mumbai} in Mumbai with chain ids 1..${mumbai}).`,
  );
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(() => client.close());
