import { promises as fs } from "node:fs";
import path from "node:path";
import type { HardhatRuntimeEnvironment } from "hardhat/types";

export interface Deployment {
  address: string;
  verifier: string;
  blockNumber: number;
}

const ROOT = path.resolve(__dirname, "..", "..");
export const DEPLOYMENTS_DIR = path.join(ROOT, "deployments");
const OUT_FILE = path.join(ROOT, "src", "index.ts");

export async function readDeployments(): Promise<Record<number, Deployment>> {
  const out: Record<number, Deployment> = {};
  let files: string[] = [];
  try {
    files = await fs.readdir(DEPLOYMENTS_DIR);
  } catch {
    return out;
  }
  for (const file of files.filter((f) => /^\d+\.json$/.test(f)).sort((a, b) => parseInt(a) - parseInt(b))) {
    const d = JSON.parse(await fs.readFile(path.join(DEPLOYMENTS_DIR, file), "utf8")) as Deployment;
    out[parseInt(file)] = { address: d.address, verifier: d.verifier, blockNumber: d.blockNumber };
  }
  return out;
}

export async function writeDeployment(chainId: number, d: Deployment): Promise<string> {
  await fs.mkdir(DEPLOYMENTS_DIR, { recursive: true });
  const file = path.join(DEPLOYMENTS_DIR, `${chainId}.json`);
  await fs.writeFile(file, JSON.stringify(d, null, 2) + "\n");
  return file;
}

export async function exportAbi(hre: HardhatRuntimeEnvironment): Promise<string> {
  const { abi } = await hre.artifacts.readArtifact("Houseful");
  const deployments = await readDeployments();
  const src = `// Generated by scripts/export-abi.ts. Do not edit by hand.

export const housefulAbi = ${JSON.stringify(abi, null, 2)} as const;

export const ATTESTATION_DOMAIN_NAME = "Houseful";
export const ATTESTATION_DOMAIN_VERSION = "1";

export const attestationTypes = {
  Attestation: [
    { name: "eventId", type: "uint256" },
    { name: "nullifier", type: "uint256" },
    { name: "wallet", type: "address" },
    { name: "purpose", type: "uint8" },
    { name: "deadline", type: "uint256" },
  ],
} as const;

export const attestationPrimaryType = "Attestation" as const;

export function attestationDomain(chainId: number, verifyingContract: \`0x\${string}\`) {
  return {
    name: ATTESTATION_DOMAIN_NAME,
    version: ATTESTATION_DOMAIN_VERSION,
    chainId,
    verifyingContract,
  } as const;
}

export const Purpose = {
  Buy: 1,
  Join: 2,
  Claim: 3,
} as const;

export type Purpose = (typeof Purpose)[keyof typeof Purpose];

export const chainIds = {
  hardhat: 31337,
  worldchainSepolia: 4801,
} as const;

export interface HousefulDeployment {
  address: \`0x\${string}\`;
  verifier: \`0x\${string}\`;
  blockNumber: number;
}

export const deployments: Record<number, HousefulDeployment> = ${JSON.stringify(deployments, null, 2)};

export function housefulAddress(chainId: number): \`0x\${string}\` | undefined {
  return deployments[chainId]?.address;
}
`;
  await fs.mkdir(path.dirname(OUT_FILE), { recursive: true });
  await fs.writeFile(OUT_FILE, src);
  return OUT_FILE;
}
